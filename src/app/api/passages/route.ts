import { NextRequest, NextResponse } from "next/server";
import prisma from "@/lib/prisma";
import { DifficultyLevel } from "@prisma/client";

export const dynamic = "force-dynamic";

// Helper function to create clean URL slug from title
function slugify(text: string): string {
  return text
    .toString()
    .toLowerCase()
    .trim()
    .replace(/\s+/g, "-") // Replace spaces with -
    .replace(/[^\w-]+/g, "") // Remove all non-word chars
    .replace(/--+/g, "-") // Replace multiple - with single -
    .replace(/^-+/, "") // Trim - from start of text
    .replace(/-+$/, ""); // Trim - from end of text
}

// GET /api/passages - List passages with optional filters
export async function GET(request: NextRequest) {
  try {
    const searchParams = request.nextUrl.searchParams;
    const difficultyParam = searchParams.get("difficulty");
    const categoryParam = searchParams.get("category");
    const searchParam = searchParams.get("q");

    // Build Prisma where query
    const whereClause: {
      isPublished: boolean;
      difficulty?: DifficultyLevel;
      category?: string;
      OR?: Array<
        | { titleEn: { contains: string; mode: "insensitive" } }
        | { titleBn: { contains: string } }
        | { summaryEn: { contains: string; mode: "insensitive" } }
      >;
    } = {
      isPublished: true,
    };

    if (
      difficultyParam &&
      Object.values(DifficultyLevel).includes(difficultyParam as DifficultyLevel)
    ) {
      whereClause.difficulty = difficultyParam as DifficultyLevel;
    }

    if (categoryParam && categoryParam !== "all") {
      whereClause.category = categoryParam;
    }

    if (searchParam && searchParam.trim()) {
      const q = searchParam.trim();
      whereClause.OR = [
        { titleEn: { contains: q, mode: "insensitive" } },
        { titleBn: { contains: q } },
        { summaryEn: { contains: q, mode: "insensitive" } },
      ];
    }

    const passages = await prisma.passage.findMany({
      where: whereClause,
      select: {
        id: true,
        slug: true,
        titleEn: true,
        titleBn: true,
        category: true,
        difficulty: true,
        readingTimeMinutes: true,
        summaryEn: true,
        summaryBn: true,
        createdAt: true,
        _count: {
          select: {
            sections: true,
            vocabularies: true,
          },
        },
      },
      orderBy: {
        createdAt: "desc",
      },
    });

    return NextResponse.json({
      success: true,
      data: passages,
    });
  } catch (error) {
    console.error("Error fetching passages:", error);
    return NextResponse.json(
      {
        success: false,
        error: "Failed to fetch passages from database",
      },
      { status: 500 }
    );
  }
}

// POST /api/passages - Upload / Seed a new passage with sections and vocabulary
export async function POST(request: Request) {
  try {
    const body = await request.json();

    const {
      titleEn,
      titleBn,
      slug,
      category = "General",
      difficulty = "BEGINNER",
      englishContent,
      bengaliContent,
      summaryEn,
      summaryBn,
      readingTimeMinutes,
      sections,
      vocabularies,
    } = body;

    // Validation
    if (!titleEn || !titleBn || !englishContent || !bengaliContent) {
      return NextResponse.json(
        {
          success: false,
          error: "Missing required fields: titleEn, titleBn, englishContent, bengaliContent",
        },
        { status: 400 }
      );
    }

    // Generate or clean slug
    const finalSlug = slug ? slugify(slug) : slugify(titleEn);

    // Calculate reading time if not provided (avg 180 words per minute)
    const wordCount = englishContent.trim().split(/\s+/).length;
    const calculatedReadingTime =
      readingTimeMinutes || Math.max(1, Math.round(wordCount / 180));

    // Prepare sections: either provided explicitly or auto-generated by splitting paragraphs
    let sectionsData: Array<{
      orderIndex: number;
      englishText: string;
      bengaliText: string;
    }> = [];

    if (Array.isArray(sections) && sections.length > 0) {
      sectionsData = sections.map((sec, idx) => ({
        orderIndex: sec.orderIndex ?? idx,
        englishText: sec.englishText.trim(),
        bengaliText: sec.bengaliText.trim(),
      }));
    } else {
      // Auto-split into paragraphs if sections were not provided manually
      const enParagraphs = englishContent
        .split(/\n\s*\n/)
        .map((p: string) => p.trim())
        .filter(Boolean);
      const bnParagraphs = bengaliContent
        .split(/\n\s*\n/)
        .map((p: string) => p.trim())
        .filter(Boolean);

      sectionsData = enParagraphs.map((enP: string, idx: number) => ({
        orderIndex: idx,
        englishText: enP,
        bengaliText: bnParagraphs[idx] || "",
      }));
    }

    // Prepare vocabulary items
    const vocabData = Array.isArray(vocabularies)
      ? vocabularies.map((v) => ({
          word: v.word.trim(),
          phonetic: v.phonetic?.trim() || null,
          partOfSpeech: v.partOfSpeech?.trim() || null,
          bengaliMeaning: v.bengaliMeaning.trim(),
          englishDefinition: v.englishDefinition?.trim() || null,
          exampleSentenceEn: v.exampleSentenceEn?.trim() || null,
          exampleSentenceBn: v.exampleSentenceBn?.trim() || null,
        }))
      : [];

    // Use Prisma transaction to upsert passage and nested records
    const newPassage = await prisma.$transaction(async (tx) => {
      // Check if slug exists, if so append timestamp
      const existing = await tx.passage.findUnique({
        where: { slug: finalSlug },
      });

      const uniqueSlug = existing
        ? `${finalSlug}-${Date.now().toString().slice(-4)}`
        : finalSlug;

      return tx.passage.create({
        data: {
          slug: uniqueSlug,
          titleEn: titleEn.trim(),
          titleBn: titleBn.trim(),
          category: category.trim(),
          difficulty: difficulty as DifficultyLevel,
          englishContent: englishContent.trim(),
          bengaliContent: bengaliContent.trim(),
          summaryEn: summaryEn?.trim() || null,
          summaryBn: summaryBn?.trim() || null,
          readingTimeMinutes: calculatedReadingTime,
          sections: {
            create: sectionsData,
          },
          vocabularies: {
            create: vocabData,
          },
        },
        include: {
          sections: true,
          vocabularies: true,
        },
      });
    });

    return NextResponse.json(
      {
        success: true,
        message: "Passage created successfully",
        data: newPassage,
      },
      { status: 201 }
    );
  } catch (error: any) {
    console.error("Error creating passage:", error);
    return NextResponse.json(
      {
        success: false,
        error: error.message || "Failed to create passage in database",
      },
      { status: 500 }
    );
  }
}
